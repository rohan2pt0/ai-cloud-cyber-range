#!/usr/bin/env python3
"""Fake cloud LLM providers for the SecuRAX sandbox.

WHY THIS EXISTS
  The sandbox runs the REAL product (real LiteLLM, real config generated by the real CLI). To test
  provider keys, fail-over and what leaves the machine WITHOUT real keys or spend, this process
  impersonates the provider endpoints at the NETWORK level: the sandbox compose override gives this
  container the provider hostnames as network aliases (api.groq.com, openrouter.ai,
  generativelanguage.googleapis.com, …) and LiteLLM trusts the sandbox CA. So the unmodified
  the generated litellm config — real provider prefixes, real keys wiring — is what gets exercised.

WHAT IT DOES
  * Answers OpenAI-compatible `…/chat/completions` (Groq, OpenRouter, OpenAI, DeepSeek, Mistral, xAI,
    Perplexity) and Gemini's native `…:generateContent`, streaming and non-streaming.
  * Every answer says `answered-by:<provider>` so a test can tell WHO answered.
  * Records every request (provider, path, auth credential, body) so a test can assert the RIGHT KEY
    reached the RIGHT provider and that PII never left the machine.
  * A control API (plain HTTP :9000) sets per-provider behaviour: ok | 500 | 401 | 429 | slow:<sec> | badjson.

Standard library + FastAPI/uvicorn only (both are in the gateway image, which the sandbox reuses).
"""
from __future__ import annotations

import asyncio
import json
import os
import time
import uuid

import uvicorn
from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse, Response, StreamingResponse

# Host header -> provider id (used in the control API and the log)
HOSTS = {
    "generativelanguage.googleapis.com": "gemini",
    "api.groq.com": "groq",
    "openrouter.ai": "openrouter",
    "api.openai.com": "openai",
    "api.deepseek.com": "deepseek",
    "api.mistral.ai": "mistral",
    "api.x.ai": "grok",
    "api.perplexity.ai": "perplexity",
    "api.anthropic.com": "anthropic",
    "opencode.ai": "opencodego",
}
# What each provider's "list models" endpoint returns (a test can change it via /ctl/models).
LIVE_MODELS: dict[str, list[str]] = {
    "gemini": ["gemini-9.1-flash", "gemini-9.2-flash-preview", "gemini-9.0-flash"],
    "groq": ["openai/gpt-oss-120b", "llama-3.1-8b-instant", "whisper-large-v3"],
    "openai": ["gpt-9-mini", "gpt-9"],
    "anthropic": ["claude-haiku-9-1", "claude-sonnet-9-1"],
    "deepseek": ["deepseek-v4-flash", "deepseek-v4-pro", "deepseek-chat"],
    "mistral": ["mistral-small-latest"],
    "grok": ["grok-9.1", "grok-9.1-image"],
    "openrouter": ["meta-llama/llama-3.3-70b-instruct:free"],
    "opencodego": ["deepseek-v4.1-flash", "deepseek-v4-flash", "deepseek-v4-flash-vision-exp", "glm-5.3-flash", "glm-5.3", "kimi-k3"],
}
DEFAULT_LIVE_MODELS = {k: list(v) for k, v in LIVE_MODELS.items()}
MODES: dict[str, str] = {}
LOG: list[dict] = []

app = FastAPI(title="fake-providers")
ctl = FastAPI(title="fake-providers-control")


def _provider(request: Request) -> str:
    host = (request.headers.get("host") or "").split(":")[0].lower()
    return HOSTS.get(host, host or "unknown")


def _credential(request: Request) -> str:
    h = request.headers
    if h.get("authorization"):
        return h["authorization"]
    for name in ("x-goog-api-key", "x-api-key", "api-key"):
        if h.get(name):
            return h[name]
    return request.query_params.get("key", "")


def _text(provider: str) -> str:
    return f"answered-by:{provider}"


def _openai_body(provider: str, model: str) -> dict:
    return {"id": "chatcmpl-" + uuid.uuid4().hex[:12], "object": "chat.completion", "created": int(time.time()),
            "model": model, "service_tier": None, "system_fingerprint": "fp_sandbox", "choices": [{"index": 0, "finish_reason": "stop",
                                         "message": {"role": "assistant", "content": _text(provider)}}],
            "usage": {"prompt_tokens": 5, "completion_tokens": 3, "total_tokens": 8}}


def _openai_stream(provider: str, model: str):
    cid = "chatcmpl-" + uuid.uuid4().hex[:12]
    base = {"id": cid, "object": "chat.completion.chunk", "created": int(time.time()), "model": model,
            "service_tier": None, "system_fingerprint": "fp_sandbox"}
    yield "data: " + json.dumps({**base, "choices": [{"index": 0, "delta": {"role": "assistant", "content": ""}, "finish_reason": None}]}) + "\n\n"
    yield "data: " + json.dumps({**base, "choices": [{"index": 0, "delta": {"content": _text(provider)}, "finish_reason": None}]}) + "\n\n"
    yield "data: " + json.dumps({**base, "choices": [{"index": 0, "delta": {}, "finish_reason": "stop"}]}) + "\n\n"
    yield "data: [DONE]\n\n"


def _gemini_body(provider: str) -> dict:
    return {"candidates": [{"content": {"parts": [{"text": _text(provider)}], "role": "model"},
                            "finishReason": "STOP", "index": 0}],
            "usageMetadata": {"promptTokenCount": 5, "candidatesTokenCount": 3, "totalTokenCount": 8},
            "modelVersion": "fake"}


@app.api_route("/{path:path}", methods=["GET", "POST", "PUT", "DELETE"])
async def provider_endpoint(path: str, request: Request):
    provider = _provider(request)
    raw = await request.body()
    try:
        body = json.loads(raw) if raw else {}
    except Exception:  # noqa: BLE001
        body = {"_raw": raw[:500].decode("utf-8", "replace")}
    LOG.append({"ts": time.time(), "provider": provider, "method": request.method, "path": "/" + path,
                "credential": _credential(request), "body": body,
                "user_agent": request.headers.get("user-agent", ""), "session": request.headers.get("x-opencode-session", "")})

    mode = MODES.get(provider, MODES.get("*", "ok"))
    if mode.startswith("slow:"):
        await asyncio.sleep(float(mode.split(":", 1)[1]))
    elif mode == "500":
        return JSONResponse({"error": {"message": f"{provider} simulated outage", "type": "server_error"}}, status_code=500)
    elif mode == "401":
        return JSONResponse({"error": {"message": "invalid api key (simulated)", "type": "auth"}}, status_code=401)
    elif mode == "429":
        return JSONResponse({"error": {"message": "rate limited (simulated)", "type": "rate_limit"}}, status_code=429,
                            headers={"retry-after": "1"})
    elif mode == "badjson":
        return Response("<<not json>>", media_type="application/json")

    model = (body or {}).get("model", "fake-model") if isinstance(body, dict) else "fake-model"
    if path.endswith("chat/completions"):
        if isinstance(body, dict) and body.get("stream"):
            return StreamingResponse(_openai_stream(provider, model), media_type="text/event-stream")
        return JSONResponse(_openai_body(provider, model))
    if ":generateContent" in path:
        return JSONResponse(_gemini_body(provider))
    if ":streamGenerateContent" in path:
        def gen():
            yield "data: " + json.dumps(_gemini_body(provider)) + "\r\n\r\n"
        return StreamingResponse(gen(), media_type="text/event-stream")
    if path.endswith("/models") or path.endswith("models"):
        ids = LIVE_MODELS.get(provider, ["fake-model"])
        if provider == "gemini":
            return JSONResponse({"models": [{"name": "models/" + i, "supportedGenerationMethods": ["generateContent"]} for i in ids]})
        return JSONResponse({"object": "list", "data": [{"id": i, "object": "model"} for i in ids]})
    return JSONResponse({"error": f"fake-providers: unhandled {request.method} /{path}"}, status_code=404)


# ───────────────────────────── control API (plain HTTP) ─────────────────────────────
@ctl.get("/ctl/health")
async def health():
    return {"ok": True, "modes": MODES, "requests": len(LOG)}


@ctl.post("/ctl/mode")
async def set_mode(request: Request):
    data = await request.json()      # {"provider": "groq" | "*", "mode": "500"}
    MODES[data.get("provider", "*")] = data.get("mode", "ok")
    return {"modes": MODES}


@ctl.post("/ctl/models")
async def set_models(request: Request):
    data = await request.json()      # {"provider": "gemini", "models": ["gemini-9.1-flash"]}
    LIVE_MODELS[data["provider"]] = data["models"]
    return {"ok": True}


@ctl.post("/ctl/reset")
async def reset():
    MODES.clear()
    LOG.clear()
    LIVE_MODELS.clear()
    LIVE_MODELS.update({k: list(v) for k, v in DEFAULT_LIVE_MODELS.items()})
    return {"ok": True}


@ctl.get("/ctl/log")
async def get_log(provider: str = ""):
    return [e for e in LOG if not provider or e["provider"] == provider]


async def main() -> None:
    crt = os.environ.get("FAKE_CERT", "/sandbox/out/certs/server.crt")
    key = os.environ.get("FAKE_KEY", "/sandbox/out/certs/server.key")
    tls = uvicorn.Server(uvicorn.Config(app, host="0.0.0.0", port=443, ssl_certfile=crt, ssl_keyfile=key,
                                        log_level="warning"))
    plain = uvicorn.Server(uvicorn.Config(ctl, host="0.0.0.0", port=9000, log_level="warning"))
    # Same provider app over plain HTTP for HOST-side tools (e.g. `./securax models`) that cannot resolve the
    # provider hostnames; they send the real Host header so the fake still knows which provider they mean.
    plain_providers = uvicorn.Server(uvicorn.Config(app, host="0.0.0.0", port=9001, log_level="warning"))
    await asyncio.gather(tls.serve(), plain.serve(), plain_providers.serve())


if __name__ == "__main__":
    asyncio.run(main())
