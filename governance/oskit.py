#!/usr/bin/env python3
"""OS kit: one set of modules, many apps (doc 95). An edition is ONE JSON file that names the app, its words and its content;
the kit's modules (Today, Inbox, Goals, Rituals, Wheel, Rhythm, Registers, Scorecard, Playbooks, Progress, Feeds, Settings)
do the work. Vantage, the CISO's operating system, is the first edition.

    ./securax os                         the editions, their modules and where each is served
    ./securax os build [ID|--all]        write guiding-map/<ID>/ (index.html, manifest, offline worker) from the kit
    ./securax os new ID --name "Name" [--from starter|vantage] [--tagline "..."]
                                         start a new app from a template edition, then build it
    ./securax os check                   every edition is valid and every built app is current (CI runs this)

Each app is one self-contained, offline page served by the estate at http://localhost:8088/<ID>/ and installable on a phone.
Its data stays on the device under its own names ("osk:<ID>:"), and syncs with the same estate sync the Life OS uses.
Standard library only. Exit codes: 0 ok, 1 check failed, 2 bad usage.
"""
from __future__ import annotations

import argparse
import hashlib
import html as _h
import json
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
GM = ROOT / "guiding-map"
KIT = GM / "kit"
EDITIONS = KIT / "editions"
# load order: core first, then every module (each registers itself; the edition decides which are switched on)
MODULES = ("today", "inbox", "goals", "rituals", "wheel", "cadence", "registers", "scorecard", "playbooks", "progress", "feeds", "settings")
EVERY = {"week", "fortnight", "month", "quarter", "half", "year"}
FIELD_TYPES = {"text", "long", "select", "date", "number", "scale"}
ID_RE = re.compile(r"^[a-z][a-z0-9-]{2,30}$")
PRINCIPLES = ROOT / "governance" / "principles.json"   # the estate's one list of principles: every app carries the core ones
WHATSNEW = KIT / "whatsnew.json"                       # what changed in the kit, shown once on each app's Today
MARK = "GENERATED by governance/oskit.py"


def rel(p: pathlib.Path) -> str:
    try:
        return str(p.relative_to(ROOT))
    except ValueError:
        return str(p)


def editions(include_templates: bool = True) -> dict[str, dict]:
    out = {}
    for p in sorted(EDITIONS.glob("*.json")):
        e = json.loads(p.read_text(encoding="utf-8"))
        if include_templates or not e.get("template"):
            out[p.stem] = e
    return out


def validate(e: dict, stem: str | None = None) -> list[str]:
    """Everything an edition can get wrong, in plain words. An empty list means it builds."""
    err: list[str] = []
    eid = e.get("id", "")
    if not ID_RE.match(eid):
        err.append(f"id {eid!r}: use 3-31 lower-case letters, digits or '-', starting with a letter")
    if stem and stem != eid:
        err.append(f"the file is named {stem}.json but its id is {eid!r}: they must match")
    for k in ("name", "tagline"):
        if not str(e.get(k, "")).strip():
            err.append(f"'{k}' is missing")
    mods = e.get("modules") or {}
    for m in mods:
        if m not in MODULES:
            err.append(f"module {m!r} is not in the kit (known: {', '.join(MODULES)})")
    regs = {r.get("id"): r for r in mods.get("registers") or []} if isinstance(mods.get("registers"), list) else {}
    if "registers" in mods and not isinstance(mods["registers"], list):
        err.append("'registers' must be a list of registers")
    nav = e.get("nav") or []
    if not nav:
        err.append("'nav' is empty: name at least one screen")
    for n in nav:
        base, _, sub = n.partition(":")
        if base not in mods:
            err.append(f"nav {n!r}: module {base!r} is not switched on under 'modules'")
        elif base == "registers" and sub not in regs:
            err.append(f"nav {n!r}: there is no register {sub!r}")
    if len(set(nav)) != len(nav):
        err.append("'nav' names a screen twice")
    for rid, r in regs.items():
        fids = [f.get("id") for f in r.get("fields") or []]
        if not rid or not re.match(r"^[a-z][a-z0-9_]*$", str(rid)):
            err.append(f"register {rid!r}: give it a short lower-case id")
        if not r.get("label"):
            err.append(f"register {rid}: 'label' is missing")
        if not fids or len(set(fids)) != len(fids):
            err.append(f"register {rid}: needs fields with unique ids")
        if r.get("title") not in fids:
            err.append(f"register {rid}: 'title' must name one of its fields")
        for f in r.get("fields") or []:
            if f.get("type") not in FIELD_TYPES:
                err.append(f"register {rid}, field {f.get('id')}: type must be one of {', '.join(sorted(FIELD_TYPES))}")
            if f.get("type") == "select" and not f.get("options"):
                err.append(f"register {rid}, field {f.get('id')}: a select needs 'options'")
        refs = list(r.get("score") or []) + [r.get("due")] + [(r.get("status") or {}).get("field"), (r.get("expiry") or {}).get("field")]
        refs += [(r.get("touch") or {}).get("last"), (r.get("touch") or {}).get("every")] + list(r.get("list") or [])
        for ref in refs:
            if ref and ref not in fids:
                err.append(f"register {rid}: refers to a field {ref!r} it does not have")
    if len(regs) != len(mods.get("registers") or []):
        err.append("two registers share an id")

    def uniq(items, what):
        ids = [i.get("id") for i in items]
        if any(not i for i in ids) or len(set(ids)) != len(ids):
            err.append(f"{what}: every item needs its own id")
    cad = (mods.get("cadence") or {}).get("items") or []
    uniq(cad, "cadence")
    for c in cad:
        if c.get("every") not in EVERY and not str(c.get("every", "")).isdigit():
            err.append(f"cadence {c.get('id')}: 'every' must be one of {', '.join(sorted(EVERY))} or a number of days")
    uniq((mods.get("rituals") or {}).get("items") or [], "rituals")
    uniq((mods.get("wheel") or {}).get("dims") or [], "wheel")
    uniq((mods.get("playbooks") or {}).get("items") or [], "playbooks")
    mets = (mods.get("scorecard") or {}).get("metrics") or []
    uniq(mets, "scorecard")
    for m in mets:
        if not isinstance(m.get("base"), (int, float)) or not isinstance(m.get("goal"), (int, float)):
            err.append(f"scorecard {m.get('id')}: 'base' and 'goal' must be numbers")
    for g in (mods.get("goals") or {}).get("starter") or []:
        for k in g.get("krs") or []:
            if k.get("b") == k.get("g"):
                err.append(f"goal starter {g.get('o')!r}: a key result needs a target different from its start")
    known = {p["id"] for p in core_principles()["principles"]}
    for x in e.get("principles") or []:
        pid = x.get("id") if isinstance(x, dict) else x
        if pid not in known:
            err.append(f"principle {pid!r} is not in governance/principles.json (add it there, so every app can use it)")
    for f in (mods.get("feeds") or {}).get("items") or []:
        if not re.match(r"^(\.\./|/)?[a-z0-9_\-/]+\.json$", str(f.get("url", "")), re.I):
            err.append(f"feed {f.get('id')}: the url must be a .json file on the same address (no other site)")
    return err


def core_principles() -> dict:
    return json.loads(PRINCIPLES.read_text(encoding="utf-8"))


def resolve(e: dict) -> dict:
    """The edition as the app sees it: the core principles always first (in the edition's words if it has its own), then the
    others it chose; the estate's north star when it has none; and the kit news that applies to it. A change to the shared
    principles or the news therefore reaches every app at its next build, and `os check` says which apps still need one."""
    core = core_principles()
    known = {p["id"]: p for p in core["principles"]}
    chosen = [x if isinstance(x, dict) else {"id": x} for x in e.get("principles") or []]
    own = {c["id"]: c for c in chosen}
    ids = [p["id"] for p in core["principles"] if p["core"]] + [c["id"] for c in chosen if not known.get(c["id"], {}).get("core")]
    out = dict(e)
    out["principles"] = [{"id": i, "name": known[i]["name"], "core": known[i]["core"], "text": own.get(i, {}).get("text") or known[i]["text"]}
                         for i in dict.fromkeys(ids) if i in known]
    out.setdefault("north_star", core["north_star"])
    news = json.loads(WHATSNEW.read_text(encoding="utf-8")) if WHATSNEW.exists() else []
    out["whatsnew"] = [n for n in news if not n.get("editions") or e.get("id") in n["editions"]][-10:]
    return out


def _script_json(e: dict) -> str:
    # JSON inside <script>: every "<" becomes \u003c, so no text in an edition can end the script or open a comment that changes
    # how the browser reads it; the line separators old JavaScript rejects are escaped too. JSON.parse reads them back unchanged.
    return (json.dumps(e, ensure_ascii=False, separators=(",", ":"))
            .replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029"))


def render(e: dict) -> dict[str, bytes]:
    """The app's files, in memory: index.html, manifest.json and sw.js."""
    e = resolve(e)
    js = (KIT / "core.js").read_text(encoding="utf-8").rstrip() + "\n" + "\n".join((KIT / "modules" / f"{m}.js").read_text(encoding="utf-8").rstrip() for m in MODULES)
    css = (KIT / "kit.css").read_text(encoding="utf-8")
    th = e.get("theme") or {}
    if th.get("accent"):
        css += f"\n:root {{ --accent:{th['accent']}; }}"
    vals = {
        "TITLE": _h.escape(f"{e['name']}: {e['tagline']}"), "DESCRIPTION": _h.escape(e.get("description", e["tagline"])),
        "BG": _h.escape(th.get("bg", "#0d1f35")), "ID": e["id"], "CSS": css, "MARK": _h.escape(e.get("mark", e["name"][:1])),
        "NAME": _h.escape(e["name"]), "TAGLINE": _h.escape(e["tagline"]), "EDITION": _script_json(e), "JS": js,
    }
    page = (KIT / "shell.html").read_text(encoding="utf-8")
    # one pass, so a value can never be re-read as a placeholder
    page = re.sub(r"\{\{([A-Z]+)\}\}", lambda m: vals[m.group(1)], page)
    h = hashlib.sha256(page.encode()).hexdigest()[:12]
    sw = (KIT / "sw.js").read_text(encoding="utf-8").replace("{{ID}}", e["id"]).replace("{{HASH}}", h)
    man = {"name": f"{e['name']}: {e['tagline']}"[:60], "short_name": e.get("short_name", e["name"])[:12], "description": e.get("description", e["tagline"]),
           "start_url": "./index.html", "scope": "./", "display": "standalone", "background_color": th.get("bg", "#0d1f35"),
           "theme_color": th.get("bg", "#0d1f35"),
           "icons": [{"src": f"icon-{s}.png", "sizes": f"{s}x{s}", "type": "image/png", "purpose": "any maskable"} for s in (192, 512)]}
    return {"index.html": page.encode(), "manifest.json": (json.dumps(man, indent=1) + "\n").encode(), "sw.js": sw.encode()}


def out_dir(eid: str, base: pathlib.Path | None = None) -> pathlib.Path:
    return (base or GM) / eid


def _safe_target(d: pathlib.Path) -> str | None:
    """Never write over something that is not an app this kit built."""
    if not d.exists():
        return None
    idx = d / "index.html"
    if idx.is_file() and MARK in idx.read_text(encoding="utf-8", errors="replace")[:2000]:
        return None
    return f"{d} exists and is not an app built by the kit: choose another id"


def build(e: dict, base: pathlib.Path | None = None) -> pathlib.Path:
    err = validate(e)
    if err:
        raise ValueError("; ".join(err))
    d = out_dir(e["id"], base)
    bad = _safe_target(d)
    if bad:
        raise ValueError(bad)
    d.mkdir(parents=True, exist_ok=True)
    for name, data in render(e).items():
        (d / name).write_bytes(data)
    for s in (192, 512):
        own = EDITIONS / f"{e['id']}-icon-{s}.png"
        shutil.copyfile(own if own.exists() else GM / f"icon-{s}.png", d / f"icon-{s}.png")
    return d


def news_problems() -> list[str]:
    probs, ids = [], set(editions())
    for i, n in enumerate(json.loads(WHATSNEW.read_text(encoding="utf-8")) if WHATSNEW.exists() else []):
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(n.get("date", ""))) or len(str(n.get("text", ""))) < 15:
            probs.append(f"whatsnew entry {i + 1}: needs a date (YYYY-MM-DD) and a sentence")
        for x in n.get("editions") or []:
            if x not in ids:
                probs.append(f"whatsnew entry {i + 1}: edition {x!r} does not exist")
    return probs


def check() -> list[str]:
    probs = news_problems()
    for stem, e in editions().items():
        probs += [f"{stem}: {m}" for m in validate(e, stem)]
        if e.get("template") or probs:
            continue
        d = out_dir(e["id"])
        for name, data in render(e).items():
            f = d / name
            if not f.exists() or f.read_bytes() != data:
                probs.append(f"{stem}: {rel(f)} is not current: run ./securax os build {e['id']}")
    return probs


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="securax os", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd")
    sub.add_parser("list")
    b = sub.add_parser("build")
    b.add_argument("id", nargs="?")
    b.add_argument("--all", action="store_true")
    n = sub.add_parser("new")
    n.add_argument("id")
    n.add_argument("--name", required=True)
    n.add_argument("--from", dest="src", default="starter")
    n.add_argument("--tagline", default="")
    sub.add_parser("check")
    a = ap.parse_args(argv)
    E = editions()
    if a.cmd in (None, "list"):
        print("Apps built from the OS kit (doc 95). One kit, many apps: each is one JSON file in guiding-map/kit/editions/.\n")
        for stem, e in E.items():
            mods = ", ".join(m for m in MODULES if m in (e.get("modules") or {}))
            where = "a template for new apps" if e.get("template") else f"http://localhost:8088/{e['id']}/"
            print(f"  {e['name']:<12} {e['tagline']}\n  {'':<12} {where}\n  {'':<12} modules: {mods}\n")
        print("Start a new one:  ./securax os new myapp --name \"My app\"   (then edit guiding-map/kit/editions/myapp.json and ./securax os build myapp)")
        return 0
    if a.cmd == "build":
        ids = [s for s, e in E.items() if not e.get("template")] if a.all or not a.id else [a.id]
        for i in ids:
            if i not in E:
                print(f"No edition {i!r}. Known: {', '.join(E)}", file=sys.stderr)
                return 2
            try:
                d = build(E[i])
            except ValueError as ex:
                print(f"✘ {i}: {ex}", file=sys.stderr)
                return 1
            print(f"✔ {E[i]['name']} built in {rel(d)}/  ->  http://localhost:8088/{i}/")
        return 0
    if a.cmd == "new":
        if a.id in E:
            print(f"{a.id!r} already exists: edit guiding-map/kit/editions/{a.id}.json", file=sys.stderr)
            return 2
        if a.src not in E:
            print(f"No template {a.src!r}. Known: {', '.join(E)}", file=sys.stderr)
            return 2
        e = json.loads(json.dumps(E[a.src]))
        e.update({"id": a.id, "name": a.name, "short_name": a.name[:12], "mark": a.name[:1].upper()})
        e.pop("template", None)
        if a.tagline:
            e["tagline"] = a.tagline
        err = validate(e) or ([_safe_target(out_dir(a.id))] if _safe_target(out_dir(a.id)) else [])
        if err:
            print("✘ " + "; ".join(err), file=sys.stderr)
            return 2
        p = EDITIONS / f"{a.id}.json"
        p.write_text(json.dumps(e, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        d = build(e)
        print(f"✔ {a.name} created: {rel(p)} (edit its words and content), built in {rel(d)}/")
        print(f"  Open it at http://localhost:8088/{a.id}/ once the estate is up. After an edit: ./securax os build {a.id}")
        return 0
    if a.cmd == "check":
        probs = check()
        for p in probs:
            print("✘ " + p)
        if not probs:
            print(f"✔ {len(E)} edition(s) valid; every built app is current")
        return 1 if probs else 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
