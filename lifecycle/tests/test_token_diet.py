"""The open-model plan has a monthly cap, and on 2026-11-18 one day of delegation used all of it: builders re-read the
generated guiding-map/index.html and the 10,000-line ops.js on every turn, and the AI review sent the generated copy
again on every push. These hold the savings."""
import importlib.util
import pathlib
import subprocess

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]


def _load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "lifecycle" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_the_builder_is_told_never_to_open_the_generated_page():
    text = (ROOT / "lifecycle" / "autobuild_ci.py").read_text("utf-8")
    assert "guiding-map/index.html (it is generated by node build.js)" in text
    assert "grep -n and then sed -n" in text


def test_the_review_leaves_generated_files_out(tmp_path):
    rv = _load("review")
    git = lambda *a: subprocess.run(["git", *a], cwd=tmp_path, check=True, capture_output=True)
    git("init", "-q"); git("config", "user.email", "t@t"); git("config", "user.name", "t")
    (tmp_path / "guiding-map").mkdir()
    (tmp_path / "guiding-map" / "ops.js").write_text("a\n"); (tmp_path / "guiding-map" / "index.html").write_text("a\n")
    git("add", "-A"); git("commit", "-q", "-m", "base")
    (tmp_path / "guiding-map" / "ops.js").write_text("b\n"); (tmp_path / "guiding-map" / "index.html").write_text("b\n")
    diff, paths = rv.change("HEAD", root=tmp_path)
    assert "guiding-map/ops.js" in paths and "guiding-map/index.html" not in paths, paths


def test_the_ai_review_runs_once_per_pr_not_on_every_push():
    wf = yaml.safe_load((ROOT / ".github/workflows/ai-review.yml").read_text("utf-8"))
    on = wf.get("on", wf.get(True))
    assert "synchronize" not in on["pull_request"]["types"]
