#!/usr/bin/env python3
"""Render gitops/core/litellm.yaml from the shipped baseline router config and the router image pinned in the compose file,
so the cluster router and the laptop router can never drift apart. `python3 lifecycle/render_core.py` rewrites it; `--check` fails if it is stale (used by tests)."""
from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
OUT = os.path.join(ROOT, "gitops", "core", "litellm.yaml")
BASELINE = os.path.join(ROOT, "local", "compose", "litellm-config.yaml")
COMPOSE = os.path.join(ROOT, "local", "compose", "docker-compose.yml")

TEMPLATE = """# GENERATED by lifecycle/render_core.py from local/compose/litellm-config.yaml — do not edit by hand.
# The shared model router every tenant gateway talks to. Provider keys come from the optional Secret `securax-providers`
# (created by `./securax grow canopy` from your local .env); the router key from `router-key`.
apiVersion: v1
kind: Namespace
metadata:
  name: securax-core
  labels:
    pod-security.kubernetes.io/enforce: baseline
    securax.io/core: "true"
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: litellm-config
  namespace: securax-core
data:
  config.yaml: |
{config}
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: litellm
  namespace: securax-core
spec:
  replicas: 2
  selector:
    matchLabels: {{ app: litellm }}
  template:
    metadata:
      labels: {{ app: litellm }}
    spec:
      automountServiceAccountToken: false
      securityContext:
        runAsNonRoot: true
        runAsUser: 10001
        runAsGroup: 10001
        seccompProfile: {{ type: RuntimeDefault }}
      containers:
        - name: litellm
          image: {image}
          args: ["--config", "/etc/litellm/config.yaml", "--port", "4000"]
          ports: [{{ containerPort: 4000 }}]
          envFrom:
            - secretRef: {{ name: router-key, optional: true }}
            - secretRef: {{ name: securax-providers, optional: true }}
          env:
            - {{ name: HF_HUB_OFFLINE, value: "1" }}
            - {{ name: TRANSFORMERS_OFFLINE, value: "1" }}
            - {{ name: HOME, value: /tmp }}
          readinessProbe: {{ httpGet: {{ path: /health/readiness, port: 4000 }}, periodSeconds: 10 }}
          livenessProbe: {{ httpGet: {{ path: /health/liveness, port: 4000 }}, initialDelaySeconds: 30 }}
          resources:
            requests: {{ cpu: 100m, memory: 512Mi }}
            limits: {{ cpu: "1", memory: 1Gi }}
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities: {{ drop: ["ALL"] }}
          volumeMounts:
            - {{ name: config, mountPath: /etc/litellm }}
            - {{ name: tmp, mountPath: /tmp }}
      volumes:
        - name: config
          configMap: {{ name: litellm-config }}
        - name: tmp
          emptyDir: {{}}
---
apiVersion: v1
kind: Service
metadata:
  name: litellm
  namespace: securax-core
spec:
  selector: {{ app: litellm }}
  ports: [{{ port: 4000, targetPort: 4000 }}]
---
# Only tenant gateways may call the router; nothing else in the cluster can.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: litellm-from-tenants
  namespace: securax-core
spec:
  podSelector:
    matchLabels: {{ app: litellm }}
  policyTypes: [Ingress]
  ingress:
    - from:
        - namespaceSelector:
            matchExpressions: [{{ key: securax.io/tenant, operator: Exists }}]
      ports: [{{ port: 4000, protocol: TCP }}]
---
# Clone the router key into every tenant namespace (Kyverno generate): the tenant chart never holds a secret.
apiVersion: kyverno.io/v1
kind: ClusterPolicy
metadata:
  name: clone-router-key
spec:
  rules:
    - name: clone-router-key
      match:
        any:
          - resources:
              kinds: [Namespace]
              selector:
                matchExpressions: [{{ key: securax.io/tenant, operator: Exists }}]
      generate:
        apiVersion: v1
        kind: Secret
        name: router-key
        namespace: "{{{{request.object.metadata.name}}}}"
        synchronize: true
        clone:
          namespace: securax-core
          name: router-key
"""


def render() -> str:
    cfg = open(BASELINE, encoding="utf-8").read().rstrip("\n")
    image = re.search(r"^\s*image:\s*(ghcr\.io/berriai/litellm\S+)", open(COMPOSE, encoding="utf-8").read(), re.M).group(1)
    return TEMPLATE.format(image=image, config="\n".join("    " + ln if ln else "" for ln in cfg.splitlines()))


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("gitops/core/litellm.yaml is " + ("current" if ok else "STALE — run: python3 lifecycle/render_core.py"))
        sys.exit(0 if ok else 1)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", OUT)
